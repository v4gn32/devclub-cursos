/*

Tipos de Dados
Em JavaScript, os tipos de dados são divididos em duas categorias principais: tipos primitivos e tipos de referência.

Tipos Primitivos:
- string: representa texto. Exemplo: let nome = "Maria";
- number: representa números. Exemplo: let idade = 30;
- boolean: representa valores verdadeiros ou falsos. Exemplo: let maiorDeIdade = true;
- null: representa a ausência intencional de valor. Exemplo: let objeto = null;
- undefined: representa uma variável não inicializada. Exemplo: let endereco;

Tipos de Referência:
- object: representa um objeto. Exemplo: let aluno = { nome: "Maria", idade: 30 };
- array: representa uma lista de valores. Exemplo: let notas = [8, 9, 10];

*/

