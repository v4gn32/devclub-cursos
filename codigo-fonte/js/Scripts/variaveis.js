// Exemplo de variáveis usando let, const e var

// let: valor pode ser alterado
let idade = 25;
console.log("Idade inicial:", idade);
idade = 26;
console.log("Idade alterada:", idade);

// const: valor não pode ser alterado
const nome = "Carlos";
console.log("Nome:", nome);
// nome = "Ana"; // Isto causaria um erro

// var: ainda funciona, mas não é recomendado
var cidade = "São Paulo";
console.log("Cidade:", cidade);
cidade = "Rio de Janeiro";
console.log("Cidade alterada:", cidade);

// Exemplos de nomes descritivos
let quantidadeDeLivros = 10;
const PI = 3.14159;
var estaChovendo = false;

console.log("Quantidade de livros:", quantidadeDeLivros);
console.log("Valor de PI:", PI);
console.log("Está chovendo?", estaChovendo);
